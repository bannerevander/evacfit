// Domain types mirror PRD §8 (Model Data). Field names are camelCase versions of the PRD columns.

export type Role = 'citizen' | 'coordinator' | 'shelter_manager' | 'volunteer'

export type Lang = 'id' | 'en'

export type NeedKey = 'noStairsRequired' | 'accessibleToiletNeeded' | 'caregiverSpaceNeeded' | 'medicalPowerRequired' | 'wheelchairVehicleNeeded'

export type FacilityType = 'medical_power' | 'caregiver_room' | 'no_stairs' | 'accessible_toilet' | 'general_capacity'

/** MTCH-5 rationale as data, so the UI can phrase it in the viewer's language. */
export interface MatchReason {
  needs: NeedKey[]
  powerAvailable?: number
  language?: string
  general?: 'keep_accessible' | 'no_better'
  people: number
  km: number
}

/** UNMT-2 deficit as data. */
export interface UnmetDetail {
  kind: 'none_has' | 'full'
  needs: NeedKey[]
  people: number
  watt: number
}

export type AlertMsg =
  | { k: 'activated'; title: string; n: number }
  | { k: 'matched'; made: number; backlog: number }
  | { k: 'closed' }
  | { k: 'checkin_unmet'; family: string; facility: FacilityType }
  | { k: 'reallocated'; family: string; shelter: string }
  | { k: 'no_alternative'; family: string }
  | { k: 'synced'; n: number }
  | { k: 'error'; code: 'no_event' | 'not_found' | 'bad_transition' | 'not_confirmed' | 'vehicle_mismatch' | 'forbidden' | 'outside_area' | 'server' }

export type FamilyStatus = 'idle' | 'waiting_match' | 'recommended' | 'confirmed' | 'in_transit' | 'arrived' | 'cancelled'

export type AssignmentStatus = 'recommended' | 'confirmed' | 'rejected' | 'in_transit' | 'arrived' | 'reallocated'

export type ShelterOperationalStatus = 'open' | 'full' | 'closed_emergency' | 'inactive'

export type VerificationStatus = 'verified' | 'unverified'

export type DisasterType = 'earthquake' | 'flood' | 'volcanic_eruption' | 'wildfire'

export type VehicleType = 'standard_car' | 'ambulance' | 'wheelchair_accessible_van' | 'bus' | 'boat'

export type Severity = 'low' | 'medium' | 'high' | 'critical'

export interface LatLng {
  lat: number
  lng: number
}

export interface FunctionalNeeds {
  noStairsRequired: boolean
  accessibleToiletNeeded: boolean
  caregiverSpaceNeeded: boolean
  medicalPowerRequired: boolean
  minPowerWattage: number
  wheelchairVehicleNeeded: boolean
  preferredLanguage: string
  infantCount: number
  pregnantCount: number
  notes: string
}

export interface Family extends LatLng {
  id: string
  code: string
  familyName: string
  memberCount: number
  contactPhone: string
  addressNotes: string
  status: FamilyStatus
  needs: FunctionalNeeds
  registeredVia: 'self' | 'caregiver' | 'field_triage'
  /** Where the family is right now, reported during an emergency; overrides lat/lng as the pickup point. */
  currentLat?: number
  currentLng?: number
  currentAt?: string
}

export interface ShelterFeatures {
  hasRamp: boolean
  rampSlopeCompliant: boolean
  doorWidthAccessible: boolean
  hasAccessibleToilet: boolean
  accessibleToiletCount: number
  hasMedicalPower: boolean
  backupGeneratorCapacityWatt: number
  hasCaregiverRooms: boolean
  supportedLanguages: string[]
}

export interface Shelter extends LatLng {
  id: string
  name: string
  address: string
  contact: string
  totalCapacity: number
  /** Evacuees already present before this operation; arrivals are derived from assignments. */
  currentOccupancy: number
  operationalStatus: ShelterOperationalStatus
  verificationStatus: VerificationStatus
  features: ShelterFeatures
}

export type RejectionCode = 'facility_power_down' | 'ramp_damaged' | 'local_capacity_full' | 'shelter_unsafe' | 'other'

export interface Assignment {
  id: string
  familyId: string
  shelterId: string
  status: AssignmentStatus
  reason: MatchReason
  distanceKm: number
  createdAt: string
  softLockExpiresAt: string
  confirmedAt?: string
  departedAt?: string
  arrivedAt?: string
  readyForPickupAt?: string
  rejectionCode?: RejectionCode
  rejectionReason?: string
  reallocatedFromId?: string
  volunteerId?: string
  vehicleType?: VehicleType
}

export interface DisasterEvent extends LatLng {
  id: string
  source: 'manual' | 'bmkg'
  type: DisasterType
  title: string
  magnitude?: number
  depthKm?: number
  radiusKm: number
  status: 'draft' | 'active' | 'closed'
  time: string
}

export interface UnmetNeed {
  id: string
  familyId: string
  shelterId?: string
  /** Aggregation key for UNMT-2. */
  missingFacilityType: FacilityType
  /** Generated by the matcher (structured) or typed by a shelter manager at check-in (free text). */
  detail?: UnmetDetail
  description?: string
  severity: Severity
  resolutionStatus: 'open' | 'in_progress' | 'resolved'
  reportedAt: string
}

export interface Volunteer {
  id: string
  name: string
  vehicleType: VehicleType
  plate: string
}

export interface OutboxItem {
  id: string
  kind: 'save_family' | 'depart' | 'check_in' | 'ready'
  at: string
  /** Supabase mode: the queued action itself, replayed when the signal returns. */
  action?: unknown
}
